/** The active-parking card on Home. Returns null when there is nothing to show. */
async function getCurrentForUser(userId) {
  const row = await bookingRepository.findCurrentForUser({
    userId,
    earlyMinutes: config.booking.checkInEarlyMinutes,
  });
  if (!row) return null;

  const booking = serializeBooking(row);

  // Live elapsed/remaining, computed server-side so two devices agree.
  if (row.status === 'CHECKED_IN' && row.checked_in_at) {
    const now = time.nowUtc();
    const elapsed = time.diffMinutes(now, time.parseInstant(row.checked_in_at)) ?? 0;
    const reserved = Number(row.duration_minutes) || 0;

    // What they would owe if they left this minute — the same function check-out
    // itself uses, so the figure on the Home card is the figure they are charged.
    // The old operator app computed `amount = seconds parked`, billing an hour as
    // ₹3,600, and the server then took Math.max(server, client).
    const area = await parkingRepository.findRawById(row.parking_id);
    const projected = pricingService.finalAmount({
      booking: { ...row, entry_time: row.checked_in_at },
      exitAt: now,
      parkingArea: area,
    });

    booking.session = {
      elapsed_minutes: Math.max(0, elapsed),
      reserved_minutes: reserved,
      remaining_minutes: Math.max(0, reserved - elapsed),
      is_overstaying: elapsed > reserved,
      projected_total_paise: projected.total_paise,
      projected_total_display: money.formatPaise(projected.total_paise),
      // Non-zero only once they are past their booked window. The client shows the
      // line only when there is one.
      overstay_paise: projected.overstay_paise,
      overstay_display:
        projected.overstay_paise > 0 ? money.formatPaise(projected.overstay_paise) : null,
    };
  }

  return booking;
}

