/** Turns a repository freedom reason into the right domain error. */
function freedomToError(reason) {
  switch (reason) {
    case 'SLOT_NOT_FOUND':
      return notFound('That slot does not exist', 'SLOT_NOT_FOUND');
    case 'SLOT_CLOSED':
      return conflict('That slot is out of service', 'SLOT_CLOSED');
    case 'SLOT_HELD':
      return DomainErrors.slotHeldByAnother();
    case 'SLOT_BOOKED':
      return DomainErrors.timeOverlap();
    default:
      return DomainErrors.slotUnavailable();
  }
}

/**
 * Refuses a window the lot is closed for.
 *
 * Separate from `assertWindowIsBookable` because it needs a query, and async. This
 * is what stops an operator's opening hours being advisory: before it existed, a
 * lot could be marked closed on Sunday and still take Sunday bookings, because
 * hours were only consulted by the discovery filter — a customer who deep-linked
 * past discovery was never checked at all.
 */
async function assertLotIsOpen({ area, start, end }) {
  // eslint-disable-next-line global-require
  const configRepository = require('../repositories/configRepository');

  const result = await configRepository.isOpenForWindow({
    parkingAreaId: area.id,
    startAt: start,
    endAt: end,
  });

  if (result.open) return;

  // Say WHICH day, using the lot's own local day rather than the server's.
  const localStart = time.addMinutes(start, Number(area.timezone_offset_minutes) || 0);
  const dayOfWeek = localStart.getUTCDay();
  const hours = await configRepository.openingHoursFor({
    parkingAreaId: area.id,
    dayOfWeek,
  });

  const dayName = [
    'Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday',
  ][dayOfWeek];

  throw conflict(
    hours
      ? `This parking area is open ${String(hours.opens_at).slice(0, 5)}–` +
          `${String(hours.closes_at).slice(0, 5)} on ${dayName}. Pick a time inside that.`
      : `This parking area is closed on ${dayName}.`,
    'PARKING_CLOSED',
    { day_of_week: dayOfWeek }
  );
}

/** Window rules, applied identically to holds and to bookings. */
function assertWindowIsBookable({ start, duration, area }) {
  const now = time.nowUtc();

  // A small negative tolerance: the user tapped "now" a few seconds ago and the
  // request took time to arrive. Anything further back is a real mistake.
  const minutesFromNow = time.diffMinutes(start, now) ?? 0;
  if (minutesFromNow < -5) {
    throw badRequest('That start time is in the past', undefined, 'START_TIME_IN_PAST');
  }

  const maxAdvance = config.booking.maxAdvanceDays * 24 * 60;
  if (minutesFromNow > maxAdvance) {
    throw badRequest(
      `Bookings can be made up to ${config.booking.maxAdvanceDays} days ahead`,
      undefined,
      'BOOKING_TOO_FAR_AHEAD'
    );
  }

  const areaMax = Number(area?.max_duration_minutes);
  const limit = Number.isFinite(areaMax) && areaMax > 0 ? areaMax : config.booking.maxDurationMinutes;
  if (duration > limit) {
    throw badRequest(
      `This parking area allows a maximum stay of ${Math.round(limit / 60)} hours`,
      undefined,
      'DURATION_EXCEEDS_LIMIT'
    );
  }
}

