/**
 * Moves a paid booking to CONFIRMED.
 *
 * Called only by paymentService, after a signature has actually been verified —
 * there is no route that reaches this with a client-supplied "payment succeeded".
 */
async function confirmPaid({ bookingId, paymentId, actorType = 'system', client = null }) {
  const run = async (tx) => {
    const moved = await bookingRepository.transition({
      bookingId,
      from: ['PENDING_PAYMENT'],
      to: 'CONFIRMED',
      client: tx,
    });

    if (!moved) {
      // Already confirmed by the other settlement path, or no longer pending.
      const current = await bookingRepository.findByIdUnscoped(bookingId, tx);
      return { booking: current, changed: false };
    }

    await bookingRepository.recordEvent(
      {
        bookingId,
        eventType: 'payment_confirmed',
        fromStatus: 'PENDING_PAYMENT',
        toStatus: 'CONFIRMED',
        actorType,
        metadata: { payment_id: paymentId },
      },
      tx
    );

    const current = await bookingRepository.findByIdUnscoped(bookingId, tx);
    return { booking: current, changed: true };
  };

  const result = client ? await run(client) : await db.withTransaction(run);

  if (result.changed && result.booking) {
    gateway.emitBookingUpdate(result.booking.user_id, serializeBooking(result.booking));
    gateway.emitOwnerBookingUpdate(result.booking.parking_owner_id, {
      type: 'booking_confirmed',
      booking: serializeBooking(result.booking),
    });
  }

  return result;
}

/**
 * Cancels a booking.
 *
 * Records the refund obligation whether or not the gateway call is enabled, and
 * frees the slot. The old implementation deleted the row, archived nothing on some
 * paths, and never told the customer what they would get back.
 */
async function cancel({ userId, bookingId, reason = null, actorType = 'customer', actorId = null }) {
  const result = await db.withTransaction(async (tx) => {
    const row = await bookingRepository.findByIdForUser({ bookingId, userId, client: tx });
    if (!row) throw notFound('That booking could not be found', 'BOOKING_NOT_FOUND');
    if (!isCancellable(row.status)) throw DomainErrors.bookingNotCancellable(row.status);

    const refund = pricingService.refundQuote({
      amountPaise: row.amount_paise ?? 0,
      entryAt: row.entry_time,
    });

    const moved = await bookingRepository.transition({
      bookingId,
      from: ['CONFIRMED', 'PENDING_PAYMENT'],
      to: 'CANCELLED',
      patch: {
        cancelled_at: new Date(),
        cancelled_by: actorType,
        cancellation_reason: reason ? String(reason).slice(0, 300) : null,
      },
      client: tx,
    });

    if (!moved) {
      // Someone else cancelled it in the meantime. Report the current state rather
      // than an error the customer cannot act on.
      const current = await bookingRepository.findByIdForUser({ bookingId, userId, client: tx });
      return { row: current, refund: null, changed: false };
    }

    // Money owed is recorded even when refunds are not being dispatched yet, so the
    // obligation lives in the database rather than in someone's memory.
    let refundRecord = null;
    if (row.payment_status === 'PAID' && refund.refund_paise > 0) {
      const payment = await paymentRepository.findPaidForBooking(bookingId, tx);
      if (payment) {
        refundRecord = await paymentRepository.createRefund(
          {
            paymentId: payment.id,
            bookingId,
            amountPaise: refund.refund_paise,
            reason: reason || 'customer_cancelled',
            status: config.features.refundsEnabled ? 'PENDING' : 'PENDING',
          },
          tx
        );
      }
    }

    // An unpaid booking's open order is closed so it cannot be paid after the fact.
    if (row.status === 'PENDING_PAYMENT') {
      await paymentRepository.abandonOpenOrders({ bookingId, reason: 'booking_cancelled' }, tx);
    }

    await bookingRepository.recordEvent(
      {
        bookingId,
        eventType: 'cancelled',
        fromStatus: row.status,
        toStatus: 'CANCELLED',
        actorType,
        actorId: actorId ?? userId,
        metadata: {
          reason,
          refund_percent: refund.refund_percent,
          refund_paise: refund.refund_paise,
          refund_id: refundRecord?.id ?? null,
        },
      },
      tx
    );

    const current = await bookingRepository.findByIdForUser({ bookingId, userId, client: tx });
    return { row: current, refund, changed: true };
  });

  if (result.changed && result.row) {
    gateway.emitSlotUpdate({
      parkingAreaId: result.row.parking_id,
      vehicleType: result.row.vehicle_type,
      slotId: result.row.parking_slot_id,
      slotNumber: result.row.slot_number,
      slotCode: result.row.slot_code,
      status: 'available',
    });
    gateway.emitBookingUpdate(userId, serializeBooking(result.row));
    gateway.emitOwnerBookingUpdate(result.row.parking_owner_id, {
      type: 'booking_cancelled',
      booking: serializeBooking(result.row),
    });
  }

  return {
    booking: serializeBooking(result.row),
    refund: result.refund,
    changed: result.changed,
  };
}

/**
 * Previews a cancellation without performing it.
 *
 * So the confirm dialog can state the actual refund rather than asking someone to
 * agree to an unknown outcome.
 */
async function cancellationPreview({ userId, bookingId }) {
  const row = await bookingRepository.findByIdForUser({ bookingId, userId });
  if (!row) throw notFound('That booking could not be found', 'BOOKING_NOT_FOUND');

  const refund = pricingService.refundQuote({
    amountPaise: row.amount_paise ?? 0,
    entryAt: row.entry_time,
  });

  return {
    is_cancellable: isCancellable(row.status),
    status: row.status,
    // Only meaningful when money actually changed hands.
    was_paid: row.payment_status === 'PAID',
    ...refund,
    refund_display: money.formatPaise(refund.refund_paise),
    retained_display: money.formatPaise(refund.retained_paise),
  };
}

/**
 * Check-in. Performed by the customer on arrival or by the operator at the barrier.
 *
 * `actorType` distinguishes the two in the audit trail, which matters in a dispute
 * about whether a car was ever actually there.
 */
async function checkIn({ bookingId, userId = null, ownerId = null, actorType = 'customer', force = false }) {
  const result = await db.withTransaction(async (tx) => {
    const row = userId
      ? await bookingRepository.findByIdForUser({ bookingId, userId, client: tx })
      : await bookingRepository.findByIdUnscoped(bookingId, tx);

    if (!row) throw notFound('That booking could not be found', 'BOOKING_NOT_FOUND');
    if (ownerId && Number(row.parking_owner_id) !== Number(ownerId)) {
      throw forbidden('That booking is not for your parking area', 'NOT_YOUR_PARKING_AREA');
    }
    if (row.status === 'CHECKED_IN') return { row, changed: false };
    if (row.status !== 'CONFIRMED') throw DomainErrors.invalidTransition(row.status, 'CHECKED_IN');

    const entry = time.parseInstant(row.entry_time);
    if (!force && !canCheckIn({ status: row.status, entry })) {
      const minutes = time.diffMinutes(entry, time.nowUtc());
      throw conflict(
        minutes > config.booking.checkInEarlyMinutes
          ? `Check-in opens ${config.booking.checkInEarlyMinutes} minutes before your entry time`
          : 'This booking is past its check-in window. Please speak to the operator.',
        'OUTSIDE_CHECK_IN_WINDOW',
        { minutes_until_entry: minutes }
      );
    }

    const moved = await bookingRepository.transition({
      bookingId,
      from: ['CONFIRMED'],
      to: 'CHECKED_IN',
      patch: {
        checked_in_at: new Date(),
        checked_in_by_owner_id: ownerId,
      },
      client: tx,
    });

    if (!moved) {
      const current = await bookingRepository.findByIdUnscoped(bookingId, tx);
      return { row: current, changed: false };
    }

    await bookingRepository.recordEvent(
      {
        bookingId,
        eventType: 'checked_in',
        fromStatus: 'CONFIRMED',
        toStatus: 'CHECKED_IN',
        actorType,
        actorId: ownerId ?? userId,
        metadata: { forced: force === true },
      },
      tx
    );

    const current = await bookingRepository.findByIdUnscoped(bookingId, tx);
    return { row: current, changed: true };
  });

  if (result.changed && result.row) {
    gateway.emitSlotUpdate({
      parkingAreaId: result.row.parking_id,
      vehicleType: result.row.vehicle_type,
      slotId: result.row.parking_slot_id,
      slotNumber: result.row.slot_number,
      slotCode: result.row.slot_code,
      status: 'booked',
    });
    gateway.emitBookingUpdate(result.row.user_id, serializeBooking(result.row));
    gateway.emitOwnerBookingUpdate(result.row.parking_owner_id, {
      type: 'checked_in',
      booking: serializeBooking(result.row),
    });
  }

  return { booking: serializeBooking(result.row), changed: result.changed };
}

/**
 * Check-out, and the final amount.
 *
 * The amount comes from `pricingService.finalAmount`, which the client cannot
 * influence. This replaces the operator app computing `amount = seconds parked` —
 * one rupee per second, so an hour billed as ₹3,600 — and the server then taking
 * `Math.max(server, client)`, which let that number win.
 */
async function checkOut({ bookingId, userId = null, ownerId = null, actorType = 'customer' }) {
  const result = await db.withTransaction(async (tx) => {
    const row = userId
      ? await bookingRepository.findByIdForUser({ bookingId, userId, client: tx })
      : await bookingRepository.findByIdUnscoped(bookingId, tx);

    if (!row) throw notFound('That booking could not be found', 'BOOKING_NOT_FOUND');
    if (ownerId && Number(row.parking_owner_id) !== Number(ownerId)) {
      throw forbidden('That booking is not for your parking area', 'NOT_YOUR_PARKING_AREA');
    }
    if (row.status === 'COMPLETED') return { row, changed: false };
    if (row.status !== 'CHECKED_IN') throw DomainErrors.invalidTransition(row.status, 'COMPLETED');

    const area = await parkingRepository.findRawById(row.parking_id, tx);
    const exitAt = time.nowUtc();

    const settlement = pricingService.finalAmount({
      booking: { ...row, entry_time: row.checked_in_at || row.entry_time },
      exitAt,
      parkingArea: area,
    });

    const moved = await bookingRepository.transition({
      bookingId,
      from: ['CHECKED_IN'],
      to: 'COMPLETED',
      patch: {
        completed_at: exitAt,
        checked_out_at: exitAt,
        exit_time: exitAt,
        checked_out_by_owner_id: ownerId,
        final_amount_paise: settlement.total_paise,
        checkout_snapshot: JSON.stringify(settlement),
      },
      client: tx,
    });

    if (!moved) {
      const current = await bookingRepository.findByIdUnscoped(bookingId, tx);
      return { row: current, changed: false, settlement: null };
    }

    await bookingRepository.recordEvent(
      {
        bookingId,
        eventType: 'checked_out',
        fromStatus: 'CHECKED_IN',
        toStatus: 'COMPLETED',
        actorType,
        actorId: ownerId ?? userId,
        metadata: settlement,
      },
      tx
    );

    // Popularity is a real count of completed stays, not the constant zero the old
    // API returned for a column that never existed.
    await db.query(
      'UPDATE parking_areas SET popularity_score = popularity_score + 1 WHERE id = $1',
      [row.parking_id],
      tx
    );

    const current = await bookingRepository.findByIdUnscoped(bookingId, tx);
    return { row: current, changed: true, settlement };
  });

  if (result.changed && result.row) {
    gateway.emitSlotUpdate({
      parkingAreaId: result.row.parking_id,
      vehicleType: result.row.vehicle_type,
      slotId: result.row.parking_slot_id,
      slotNumber: result.row.slot_number,
      slotCode: result.row.slot_code,
      status: 'available',
    });
    gateway.emitBookingUpdate(result.row.user_id, serializeBooking(result.row));
    gateway.emitOwnerBookingUpdate(result.row.parking_owner_id, {
      type: 'checked_out',
      booking: serializeBooking(result.row),
    });
  }

  return {
    booking: serializeBooking(result.row),
    settlement: result.settlement,
    changed: result.changed,
  };
}

