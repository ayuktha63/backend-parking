async function listForUser({ userId, bucket, limit = 20, offset = 0 }) {
  const rows = await bookingRepository.listForUser({ userId, bucket, limit, offset });
  const hasMore = rows.length > limit;
  const page = hasMore ? rows.slice(0, limit) : rows;

  return {
    items: page.map((r) => serializeBooking(r)),
    page: { limit, offset, has_more: hasMore },
  };
}

async function getForUser({ userId, bookingId }) {
  const row = await bookingRepository.findByIdForUser({ bookingId, userId });
  if (!row) throw notFound('That booking could not be found', 'BOOKING_NOT_FOUND');

  const [events, refunds] = await Promise.all([
    bookingRepository.listEvents(bookingId),
    paymentRepository.listRefundsForBooking(bookingId),
  ]);

  return {
    ...serializeBooking(row),
    // The timeline the customer sees on the booking detail screen. Only the events
    // that mean something to them; internal ones stay in the table.
    timeline: events
      .filter((e) => CUSTOMER_VISIBLE_EVENTS.has(e.event_type))
      .map((e) => ({
        type: e.event_type,
        label: eventLabel(e.event_type),
        at: time.toIso(e.created_at),
      })),
    refunds: refunds.map((r) => ({
      id: r.id,
      amount_paise: r.amount_paise,
      amount_display: money.formatPaise(r.amount_paise),
      status: r.status,
      processed_at: r.processed_at ? time.toIso(r.processed_at) : null,
    })),
  };
}

const CUSTOMER_VISIBLE_EVENTS = new Set([
  'created',
  'payment_confirmed',
  'checked_in',
  'checked_out',
  'cancelled',
  'expired',
  'no_show',
]);

function eventLabel(type) {
  switch (type) {
    case 'created':
      return 'Booking created';
    case 'payment_confirmed':
      return 'Payment confirmed';
    case 'checked_in':
      return 'Checked in';
    case 'checked_out':
      return 'Checked out';
    case 'cancelled':
      return 'Cancelled';
    case 'expired':
      return 'Expired — payment not completed';
    case 'no_show':
      return 'Marked as missed';
    default:
      return type;
  }
}

