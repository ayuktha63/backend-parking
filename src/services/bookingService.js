'use strict';

/**
 * The booking lifecycle.
 *
 * ┌──────────┐  hold   ┌──────┐  create  ┌─────────────────┐  pay   ┌───────────┐
 * │ AVAILABLE│────────▶│ HELD │─────────▶│ PENDING_PAYMENT │───────▶│ CONFIRMED │
 * └──────────┘         └──────┘          └─────────────────┘        └───────────┘
 *       ▲                  │                      │                       │
 *       │  expire/release  │        expire/fail   │             check-in  │
 *       └──────────────────┴──────────────────────┘                       ▼
 *                                                                  ┌────────────┐
 *                                    cancel ◀────────────────────  │ CHECKED_IN │
 *                                                                  └────────────┘
 *                                                                         │
 *                                                             check-out   ▼
 *                                                                  ┌───────────┐
 *                                                                  │ COMPLETED │
 *                                                                  └───────────┘
 *
 * Four invariants, each of which the previous implementation broke:
 *
 *   1. THE SERVER DECIDES THE AMOUNT. A request never carries a price. The quote
 *      is recomputed here and stored on the booking; the payment order is created
 *      from that stored number.
 *
 *   2. THE SERVER DECIDES WHOSE BOOKING IT IS. Every read and every transition is
 *      predicated on `user_id`. The old API identified a customer by a phone number
 *      in the URL, so anyone could cancel anyone's booking.
 *
 *   3. NO STATE IS REACHED BY DELETION. Cancelling, expiring and completing are all
 *      `transition()` plus a `booking_events` row.
 *
 *   4. TRANSITIONS ARE CONDITIONAL AND THEREFORE IDEMPOTENT. `transition()` matches
 *      on the expected current status; a second concurrent attempt matches nothing
 *      and is reported as "already done", not as a failure.
 */

